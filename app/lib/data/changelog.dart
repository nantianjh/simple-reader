/// 面向用户的**更新内容**记录 —— 版本变更时首次启动弹出的那个框的数据源。
///
/// 维护约定（2026-09-22 用户要求，属硬约束）：
/// * **每次改动（一次 git 提交算一次）都要顺手把用户能感知的变化写进来**，
///   写进最上面那一条（当前正在开发的版本）；
/// * 只写**用户能感知**的变化 —— 新增功能、行为变化、修复用户遇到过的毛病；
///   不写重构、测试、架构、字段改名、构建与 CI 之类的开发级变更；
/// * 措辞站在用户视角描述"你看到什么不一样了"，不暴露端点与内部实现；
/// * 版本号必须与 [AppInfo.version]、`pubspec.yaml` 三者一致
///   （`app_info_version_test.dart` 守着前两者的漂移，这里的对应关系靠人工守）。
///
/// 为什么是常量表而不是文件/接口：工程约定零第三方运行时依赖、也不引入资源
/// 打包流程，一个 const 列表既能在编译期校验格式，又不需要任何 IO；
/// 内容更新只随版本发布走，本来就不需要热更。
///
/// 历史缺口：1.9.0 之前没有记录（本机制自 1.9.6 起建立）。从更早版本升级上来
/// 的用户只会看到其"上次看过版本"之后、且在表中有记录的那部分。
library;

/// 一个版本的更新记录。
class ReleaseNote {
  const ReleaseNote({
    required this.version,
    required this.date,
    required this.changes,
  });

  /// 版本号，需与 [AppInfo.version] 一致。
  final String version;

  /// 发布日期（`YYYY-MM-DD`，仅展示用；刻意用字符串以便整表 const 化）。
  final String date;

  /// 用户能感知的变化条目，一条一句话。
  final List<String> changes;
}

