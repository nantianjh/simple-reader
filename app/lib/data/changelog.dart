  /// 当前开发版本的更新条目（表头那条）。行为兜底用：表为空时返回空列表。
  static ReleaseNote? get current => releases.isEmpty ? null : releases.first;

  /// 取「比 [fromVersion] 新」的更新记录（新版本在前）。
  ///
  /// 命中 [fromVersion] 即停止收集；表中找不到它（更早的版本、或版本号漂移）
  /// 时返回全部记录 —— 宁可多展示几条，也不要让用户以为"没有任何更新"。
  static List<ReleaseNote> since(String? fromVersion) {
    if (fromVersion == null || fromVersion.isEmpty) return releases;
    final out = <ReleaseNote>[];
    for (final r in releases) {
      if (r.version == fromVersion) break;
      out.add(r);
    }
    return out.isEmpty ? releases : out;
  }
